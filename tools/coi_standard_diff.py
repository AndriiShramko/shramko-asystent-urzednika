#!/usr/bin/env python3
"""Compare the standard sections of the partner's two reference exports.

The composer's library of standard sections is taken from these exports. This tool shows, section by
section, whether the two exports agree once ids are ignored, and what differs, so the library knows
which parts are constant and which are parameters.

  python tools/coi_standard_diff.py            # writes contracts/coi/standard-sections-diff.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.coi_paths import coi_dir  # noqa: E402

DROP = {"id", "questionOrder", "x", "y", "rows", "cols"}


def load(folder_prefix: str) -> dict:
    folder = next(p for p in sorted(coi_dir().iterdir()) if p.name.startswith(folder_prefix))
    path = next(p for p in sorted(folder.iterdir()) if p.name.startswith("konfiguracja_form") and p.suffix == ".json")
    return json.loads(path.read_text(encoding="utf-8"))


def norm(obj):
    if isinstance(obj, dict):
        return {k: norm(v) for k, v in sorted(obj.items()) if k not in DROP}
    if isinstance(obj, list):
        return [norm(v) for v in obj]
    return obj


def sections(form: dict) -> dict:
    out = {}
    for tab in form["tabs"]:
        for q in tab["questions"]:
            f = q["field"]
            out[f["techName"]] = {"page": tab["title"], "title": f.get("title"), "has_state": bool(f.get("states")), "field": f}
    return out


def comp_map(section_field: dict) -> dict:
    return {c["field"]["techName"]: c["field"] for c in section_field.get("repeatingSectionGrid") or []}


def differences(a: dict, b: dict) -> list[str]:
    na, nb = norm(a), norm(b)
    out = []
    for key in sorted(set(na) | set(nb)):
        if na.get(key) != nb.get(key):
            va, vb = json.dumps(na.get(key), ensure_ascii=False), json.dumps(nb.get(key), ensure_ascii=False)
            out.append("%s: `%s` vs `%s`" % (key, va[:70], vb[:70]))
    return out


def main() -> None:
    a, b = sections(load("reference-01")), sections(load("reference-05"))
    lines = [
        "# Standard sections: the partner's two reference exports compared",
        "",
        "Generated by `python tools/coi_standard_diff.py` from reference sets 1 and 5 (ids, order and grid ignored). Do not edit by hand.",
        "A section that is identical in both exports is a constant of the library. A difference is either a parameter (office name, register source) or an inconsistency of the exports to ask about.",
        "",
        "| Section (`techName`) | Page | In set 1 | In set 5 | Components 1 / 5 | Verdict | Differences |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in sorted(set(a) | set(b), key=lambda n: (n not in a, n)):
        sa, sb = a.get(name), b.get(name)
        if sa and sb:
            ca, cb = comp_map(sa["field"]), comp_map(sb["field"])
            notes = []
            only_a, only_b = sorted(set(ca) - set(cb)), sorted(set(cb) - set(ca))
            if only_a:
                notes.append("only in 1: " + ", ".join(only_a))
            if only_b:
                notes.append("only in 5: " + ", ".join(only_b))
            for t in sorted(set(ca) & set(cb)):
                d = differences(ca[t], cb[t])
                if d:
                    notes.append("`%s` → %s" % (t, "; ".join(d)))
            head = differences({k: v for k, v in sa["field"].items() if k != "repeatingSectionGrid"}, {k: v for k, v in sb["field"].items() if k != "repeatingSectionGrid"})
            if head:
                notes.insert(0, "section itself → " + "; ".join(head))
            verdict = "identical" if not notes else "differs"
            lines.append("| `%s` | %s | yes | yes | %d / %d | %s | %s |" % (name, sa["page"], len(ca), len(cb), verdict, "<br>".join(n.replace("|", "\\|") for n in notes)))
        else:
            s = sa or sb
            lines.append("| `%s` | %s | %s | %s | %d | only in one | title: %s |" % (name, s["page"], "yes" if sa else "no", "yes" if sb else "no", len(comp_map(s["field"])), s["title"]))
    out = ROOT / "contracts" / "coi" / "standard-sections-diff.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    same = sum(1 for line in lines if "| identical |" in line)
    diff = sum(1 for line in lines if "| differs |" in line)
    one = sum(1 for line in lines if "| only in one |" in line)
    print("written %s: identical %d, differs %d, only in one %d" % (out.relative_to(ROOT), same, diff, one))


if __name__ == "__main__":
    main()
