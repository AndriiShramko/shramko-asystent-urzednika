// Lists every installed package with its licence and fails on anything outside MIT, BSD, Apache, ISC (AGENTS.md rule 4).
// Usage: node scripts/licences.mjs [--write]   (--write refreshes LICENCES-FRONTEND.md)
import { readdirSync, readFileSync, existsSync, writeFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0'])
const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

function allowed(expr) {
  const alternatives = expr.replace(/[()]/g, '').split(/\s+OR\s+/)
  return alternatives.some((alt) => alt.split(/\s+AND\s+/).every((x) => ALLOWED.has(x.trim())))
}

const found = new Map()
function scan(dir) {
  if (!existsSync(dir)) return
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue
    const p = join(dir, name)
    if (!statSync(p).isDirectory()) continue
    if (name.startsWith('@')) { scan(p); continue }
    const manifest = join(p, 'package.json')
    if (existsSync(manifest)) {
      const m = JSON.parse(readFileSync(manifest, 'utf8'))
      let lic = typeof m.license === 'string' ? m.license : m.license?.type ?? (m.licenses ? m.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN')
      found.set(`${m.name}@${m.version}`, lic)
    }
    scan(join(p, 'node_modules'))
  }
}
scan(join(root, 'node_modules'))

const rows = [...found].sort(([a], [b]) => a.localeCompare(b))
const bad = rows.filter(([, l]) => !allowed(l))
const runtime = Object.keys(pkg.dependencies ?? {})
const lines = [
  '# Front-end licences (apps/review-web)',
  '',
  'Generated by `node scripts/licences.mjs --write`. Allowed: MIT, ISC, BSD-2-Clause, BSD-3-Clause, Apache-2.0.',
  '',
  `**In the shipped bundle (dist/):** our own code only. Runtime dependencies in package.json: ${runtime.length ? runtime.join(', ') : 'none'}. No font, script or style is loaded from the network.`,
  '',
  `**Build and test tooling (not shipped):** ${rows.length} packages, ${bad.length} outside the allowed list.`,
  '',
  '| Package | Licence | Allowed |',
  '|---|---|---|',
  ...rows.map(([n, l]) => `| ${n} | ${l} | ${allowed(l) ? 'yes' : '**NO: ask the lead**'} |`),
  ''
]
if (process.argv.includes('--write')) writeFileSync(join(root, 'LICENCES-FRONTEND.md'), lines.join('\n'))
console.log(`${rows.length} packages, ${bad.length} outside the allowed list, runtime dependencies: ${runtime.length}`)
for (const [n, l] of bad) console.log(`NOT ALLOWED: ${n} (${l})`)
process.exit(bad.length || runtime.length ? 1 : 0)
